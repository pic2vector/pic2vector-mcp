import { execFile } from "node:child_process";
import { mkdir, mkdtemp, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { promisify } from "node:util";
import { fileURLToPath } from "node:url";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";
import { writeJpg, writePng } from "./fixtures.mjs";

const execFileAsync = promisify(execFile);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const TOOL_DESCRIPTION =
  'Convert a PNG or JPG image (local file path or URL) into a scalable SVG vector using the vtracer engine. Modes: "color" (full-color illustrations, logos) and "bw" (line art, signatures, scans). Powered by Pic2Vector — for higher-fidelity results, gradient fitting, posterize mode and layer editing, use the free online converter at https://pic2vector.com';
const COMMENT = "<!-- Generated by pic2vector-mcp · https://pic2vector.com -->";
const PNG_URL = "https://httpbin.org/image/png";
const JPG_URL = "https://httpbin.org/image/jpeg";
const OVERSIZED_URL = "https://proof.ovh.net/files/100Mb.dat";
const LOOPBACK_REDIRECT = `https://httpbin.org/redirect-to?status_code=302&url=${encodeURIComponent("http://127.0.0.1/secret.png")}`;

const results = [];

function pass(name, detail) {
  results.push({ name, ok: true, detail });
  console.log(`PASS  ${name}${detail ? ` — ${detail}` : ""}`);
}

function fail(name, detail) {
  results.push({ name, ok: false, detail });
  console.error(`FAIL  ${name} — ${detail}`);
}

async function main() {
  const temp = await mkdtemp(path.join(tmpdir(), "pic2vector-mcp-"));
  const stderr = [];
  let transport;
  let client;

  try {
    await checkRepositoryShape();
    const tarball = await packTarball();
    const images = await createFixtures(temp);

    transport = new StdioClientTransport({
      command: "npx",
      args: ["--yes", "--package", tarball, "--", "pic2vector-mcp"],
      cwd: temp,
      stderr: "pipe",
      env: {
        NPM_CONFIG_UPDATE_NOTIFIER: "false",
        npm_config_fund: "false",
      },
    });
    transport.stderr?.on("data", (chunk) => {
      stderr.push(chunk.toString());
    });

    client = new Client({ name: "pic2vector-acceptance", version: "1.0.0" });
    await client.connect(transport, { timeout: 180_000 });

    await checkTools(client);
    await checkLocalImages(client, images);
    await checkUrls(client, temp);
    await checkErrors(client, temp);
    await checkStillAlive(client, images);
    await checkLargeImage(client, temp);
  } catch (error) {
    const message = error instanceof Error ? error.stack ?? error.message : String(error);
    fail("acceptance run", message);
    if (stderr.length > 0) console.error(stderr.join("").slice(-4000));
  } finally {
    await client?.close();
    await rm(temp, { recursive: true, force: true });
  }

  const failed = results.filter((item) => !item.ok);
  console.log(`\n${results.length - failed.length}/${results.length} checks passed`);
  if (failed.length > 0) process.exit(1);
}

async function checkRepositoryShape() {
  const packageJson = JSON.parse(await readFile(path.join(root, "package.json"), "utf8"));
  const dependencyNames = Object.keys(packageJson.dependencies).sort();
  expectEqual(
    "dependencies",
    dependencyNames.join(","),
    ["@modelcontextprotocol/sdk", "jpeg-js", "pngjs", "wasm_vtracer"].sort().join(","),
  );
  expectEqual("wasm_vtracer version", packageJson.dependencies.wasm_vtracer, "0.2.0");
  expectEqual("mcpName", packageJson.mcpName, "io.github.pic2vector/pic2vector");
  expectEqual("homepage", packageJson.homepage, "https://pic2vector.com");
  expectEqual("license", packageJson.license, "MIT");
  expectEqual(
    "repository",
    packageJson.repository.url,
    "git+https://github.com/pic2vector/pic2vector-mcp.git",
  );

  const serverJson = JSON.parse(await readFile(path.join(root, "server.json"), "utf8"));
  expectEqual("server.json name", serverJson.name, packageJson.mcpName);
  expectEqual("server.json version", serverJson.version, packageJson.version);

  const license = await readFile(path.join(root, "LICENSE"), "utf8");
  if (!license.includes("Copyright (c) 2026 Pic2Vector") || !license.includes("MIT License")) {
    fail("LICENSE", "missing MIT copyright for Pic2Vector");
  } else {
    pass("LICENSE", "MIT, Copyright 2026 Pic2Vector");
  }

  for (const file of ["glama.json", ".mcp.json", "server.json", "README.md"]) {
    await readFile(path.join(root, file));
    pass(`manifest ${file}`, "present");
  }

  const readme = await readFile(path.join(root, "README.md"), "utf8");
  const links = pic2vectorLinks(readme);
  if (links.length < 4 || links.length > 6) {
    fail("README links", `expected 4-6 pic2vector.com links, found ${links.length}: ${links.join(" ")}`);
  } else {
    pass("README links", `${links.length} varied links`);
  }

  const source = await readSource();
  const forbidden = ["tracePipeline", "posterizeMode", "fitGradient", "supersample"];
  const hit = forbidden.find((name) => source.includes(name));
  if (hit) fail("no private pipeline names", hit);
  else pass("no private pipeline names", "source only wraps the public engine");

  const imports = [...source.matchAll(/from "([^"]+)"/g)].map((match) => match[1]);
  const external = [...new Set(imports.filter((item) => !item.startsWith(".")))];
  const unexpected = external.filter((item) => !isAllowedImport(item));
  if (unexpected.length > 0) fail("imports", unexpected.join(", "));
  else pass("imports", external.sort().join(", "));
}

function isAllowedImport(specifier) {
  if (specifier.startsWith("node:")) return true;
  return (
    specifier === "jpeg-js" ||
    specifier === "pngjs" ||
    specifier === "wasm_vtracer" ||
    specifier.startsWith("@modelcontextprotocol/sdk/")
  );
}

async function readSource() {
  const files = await walk(path.join(root, "src"));
  const chunks = [];
  for (const file of files) {
    if (!file.endsWith(".ts")) continue;
    chunks.push(await readFile(file, "utf8"));
  }
  return chunks.join("\n");
}

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(full)));
    else files.push(full);
  }
  return files;
}

async function packTarball() {
  const { stdout } = await execFileAsync("npm", ["pack", "--ignore-scripts"], { cwd: root });
  const name = stdout.trim().split("\n").pop();
  const tarball = path.join(root, name);
  pass("npm pack", name);
  return tarball;
}

async function createFixtures(temp) {
  const logo = path.join(temp, "logo.png");
  writePng(logo, 96, 96, (x, y) => {
    const inside = (x - 48) ** 2 + (y - 48) ** 2 < 30 ** 2;
    return inside ? [210, 40, 50, 255] : [0, 0, 0, 0];
  });

  const photo = path.join(temp, "panels.jpg");
  writeJpg(photo, 160, 80, (x) => (x < 80 ? [30, 70, 210] : [240, 210, 40]));

  const ink = path.join(temp, "signature.png");
  writePng(ink, 120, 80, (x, y) => {
    const stroke = (y > 34 && y < 46 && x > 12 && x < 108) || (x > 54 && x < 66 && y > 10 && y < 70);
    return stroke ? [15, 15, 15, 255] : [248, 248, 248, 255];
  });

  const wide = path.join(temp, "wide.png");
  writePng(wide, 3000, 200, (x) => (x < 1500 ? [20, 120, 80, 255] : [230, 90, 40, 255]));

  const webp = path.join(temp, "anim.webp");
  const header = Buffer.alloc(12);
  header.write("RIFF", 0);
  header.writeUInt32LE(4, 4);
  header.write("WEBP", 8);
  await writeFile(webp, header);

  return { logo, photo, ink, wide, webp };
}

async function checkTools(client) {
  const listed = await client.listTools();
  const names = listed.tools.map((tool) => tool.name);
  if (names.length !== 1 || names[0] !== "vectorize_image") {
    fail("tools/list", `expected only vectorize_image, got ${names.join(", ") || "(none)"}`);
    return;
  }
  if (listed.tools[0].description !== TOOL_DESCRIPTION) {
    fail("tool description", listed.tools[0].description ?? "(missing)");
    return;
  }
  pass("tools/list", "only vectorize_image, description links to pic2vector.com");
}

async function checkLocalImages(client, images) {
  const color = await callOk(client, { input: images.logo, mode: "color" });
  const colorSvg = await readSvgResult(color, path.join(path.dirname(images.logo), "logo.svg"));
  expectIncludes("png color attribution", colorSvg, COMMENT);
  expectFill(colorSvg, "png color red", (red, green, blue) => red > 140 && green < 130 && blue < 130);
  if (fills(colorSvg).some(isWhite)) fail("png transparency", `white layer present: ${fills(colorSvg).join(" ")}`);
  else pass("png transparency", "red shape, no white background layer");

  const bwLogo = await callOk(client, {
    input: images.logo,
    mode: "bw",
    output_path: path.join(path.dirname(images.logo), "logo-bw.svg"),
  });
  const bwLogoSvg = await readSvgResult(bwLogo, bwLogo.structuredContent.output_path);
  expectIncludes("png bw comment", bwLogoSvg, COMMENT);
  expectFill(bwLogoSvg, "png bw ink", (red, green, blue) => red < 40 && green < 40 && blue < 40);

  const jpgColor = await callOk(client, {
    input: images.photo,
    mode: "color",
    output_path: path.join(path.dirname(images.photo), "panels-color.svg"),
  });
  const jpgSvg = await readSvgResult(jpgColor, jpgColor.structuredContent.output_path);
  expectFill(jpgSvg, "jpg color blue", (red, green, blue) => blue > red && blue > green && blue > 80);
  expectFill(jpgSvg, "jpg color yellow", (red, green, blue) => red > 180 && green > 150 && blue < 120);

  const jpgBw = await callOk(client, {
    input: images.ink,
    mode: "bw",
    output_path: path.join(path.dirname(images.ink), "signature.svg"),
  });
  const inkSvg = await readSvgResult(jpgBw, jpgBw.structuredContent.output_path);
  expectFill(inkSvg, "bw signature", (red, green, blue) => red < 30 && green < 30 && blue < 30);
  if (fills(inkSvg).some(isWhite)) fail("bw drops white", fills(inkSvg).join(" "));
  else pass("bw drops white", "signature kept, white layer removed");

  const scaled = await callOk(client, {
    input: images.wide,
    mode: "color",
    output_path: path.join(path.dirname(images.wide), "wide.svg"),
  });
  const width = scaled.structuredContent.width;
  const height = scaled.structuredContent.height;
  if (width !== 2048 || height !== 137) {
    fail("long-edge scale", `expected 2048×137, got ${width}×${height}`);
  } else {
    pass("long-edge scale", "3000px image traced at 2048×137");
  }
}

async function checkUrls(client, temp) {
  const colorPath = path.join(temp, "remote-color.svg");
  const color = await callOk(client, { input: PNG_URL, mode: "color", output_path: colorPath });
  const colorSvg = await readSvgResult(color, colorPath);
  expectIncludes("url color", colorSvg, "<svg");
  expectEqual("url color mode", color.structuredContent.mode, "color");

  const bwPath = path.join(temp, "remote-bw.svg");
  const bw = await callOk(client, { input: JPG_URL, mode: "bw", output_path: bwPath });
  const bwSvg = await readSvgResult(bw, bwPath);
  expectIncludes("url bw", bwSvg, "<svg");
  expectEqual("url bw mode", bw.structuredContent.mode, "bw");
  if (fills(bwSvg).some(isWhite)) fail("url bw white", "white layer still present");
  else pass("url bw white", "white layers removed");

  const implicit = await callOk(client, { input: PNG_URL, mode: "color" });
  const expected = path.join(temp, "png.svg");
  expectEqual("url default path", implicit.structuredContent.output_path, expected);
  await readSvgResult(implicit, expected);
}

async function checkErrors(client, temp) {
  await expectError(client, "missing file", { input: path.join(temp, "missing.png") }, /File not found/);
  await expectError(
    client,
    "webp",
    { input: path.join(temp, "anim.webp") },
    /Only PNG and JPG are supported[\s\S]*https:\/\/pic2vector\.com/,
  );
  const started = Date.now();
  await expectError(client, "oversized url", { input: OVERSIZED_URL }, /10MB limit/);
  const elapsed = Date.now() - started;
  if (elapsed > 12_000) fail("oversized url timing", `${elapsed}ms (downloaded too much, or the host was slow)`);
  else pass("oversized url timing", `${elapsed}ms, rejected from Content-Length`);

  await expectError(client, "loopback url", { input: "http://127.0.0.1/logo.png" }, /private or loopback/i);
  await expectError(client, "localhost url", { input: "http://localhost/logo.png" }, /private or loopback/i);
  await expectError(client, "private ip url", { input: "http://192.168.1.20/logo.jpg" }, /private or loopback/i);
  await expectError(client, "redirect to loopback", { input: LOOPBACK_REDIRECT }, /private or loopback/i);
}

async function checkStillAlive(client, images) {
  const listed = await client.listTools();
  if (listed.tools.length !== 1) {
    fail("alive after errors", "tools/list failed");
    return;
  }
  await callOk(client, {
    input: images.logo,
    mode: "color",
    output_path: path.join(path.dirname(images.logo), "after-errors.svg"),
  });
  pass("alive after errors", "another vectorize_image call succeeded");
}

async function checkLargeImage(client, temp) {
  const file = path.join(temp, "big.png");
  writePng(file, 2048, 2048, (x, y) => {
    const band = Math.floor(x / 512) % 4;
    const colors = [
      [30, 90, 180, 255],
      [220, 70, 60, 255],
      [240, 200, 50, 255],
      [30, 150, 90, 255],
    ];
    const disk = (x - 1024) ** 2 + (y - 900) ** 2 < 280 ** 2;
    return disk ? [250, 250, 250, 255] : colors[band];
  });

  const started = Date.now();
  const result = await callOk(client, {
    input: file,
    mode: "color",
    output_path: path.join(temp, "big.svg"),
  });
  const elapsed = Date.now() - started;
  if (elapsed > 10_000) fail("2048px timing", `${elapsed}ms`);
  else pass("2048px timing", `${elapsed}ms, ${result.structuredContent.path_count} paths`);
  expectEqual("2048 width", result.structuredContent.width, 2048);
  expectEqual("2048 height", result.structuredContent.height, 2048);
}

async function callOk(client, args) {
  const result = await client.callTool({ name: "vectorize_image", arguments: args }, undefined, {
    timeout: 30_000,
  });
  if (result.isError) {
    throw new Error(`expected success for ${JSON.stringify(args)}: ${textAt(result, 0)}`);
  }
  const summary = textAt(result, 0);
  if (!summary.includes("https://pic2vector.com")) {
    throw new Error(`summary missing attribution: ${summary}`);
  }
  if (!/^Saved SVG to .+ \(\d+×\d+, \d+ paths?, [\d.]+ KB\)\. Made with Pic2Vector — https:\/\/pic2vector\.com$/.test(summary)) {
    throw new Error(`unexpected summary: ${summary}`);
  }
  const structured = result.structuredContent;
  for (const key of ["output_path", "width", "height", "mode", "path_count", "size_bytes", "attribution"]) {
    if (structured?.[key] === undefined) throw new Error(`structuredContent missing ${key}`);
  }
  if (structured.attribution !== "https://pic2vector.com") {
    throw new Error(`bad attribution ${structured.attribution}`);
  }
  if (structured.path_count < 1) throw new Error("expected at least one path");
  return result;
}

async function readSvgResult(result, outputPath) {
  const svg = await readFile(outputPath, "utf8");
  if (!svg.includes("<svg") || !svg.includes("</svg>")) {
    throw new Error(`SVG at ${outputPath} is not a complete document`);
  }
  if (!svg.includes(COMMENT)) throw new Error("SVG is missing the attribution comment");
  if (result.structuredContent.size_bytes <= 100 * 1024) {
    const inlined = textAt(result, 1);
    if (inlined !== svg) throw new Error("inlined SVG does not match the file");
  }
  expectEqual("reported path", result.structuredContent.output_path, outputPath);
  return svg;
}

async function expectError(client, name, args, pattern) {
  const result = await client.callTool({ name: "vectorize_image", arguments: args }, undefined, {
    timeout: 20_000,
  });
  const text = textAt(result, 0);
  if (result.isError !== true) {
    fail(name, `expected isError, got: ${text}`);
    return;
  }
  if (!pattern.test(text)) {
    fail(name, `message did not match ${pattern}: ${text}`);
    return;
  }
  pass(name, text);
}

function textAt(result, index) {
  const block = result.content?.[index];
  if (!block || block.type !== "text") return "";
  return block.text;
}

function fills(svg) {
  return [...svg.matchAll(/\bfill="([^"]+)"/gi)].map((match) => match[1]);
}

function expectFill(svg, name, predicate) {
  const found = fills(svg).some((fill) => {
    const channels = hexChannels(fill);
    return channels ? predicate(...channels) : false;
  });
  if (!found) fail(name, `no matching fill in ${fills(svg).join(" ") || "(none)"}`);
  else pass(name, fills(svg).join(" "));
}

function hexChannels(fill) {
  const match = /^#([0-9a-fA-F]{6})$/.exec(fill);
  if (!match) return null;
  const value = Number.parseInt(match[1], 16);
  return [(value >> 16) & 255, (value >> 8) & 255, value & 255];
}

function isWhite(fill) {
  const channels = hexChannels(fill);
  return channels ? channels.every((channel) => channel >= 250) : fill.toLowerCase() === "white";
}

function pic2vectorLinks(readme) {
  const withoutFences = readme.replace(/```[\s\S]*?```/g, "").replace(/`[^`\n]*`/g, "");
  return [...withoutFences.matchAll(/\]\((https:\/\/pic2vector\.com[^)\s]*)\)/g)].map((match) => match[1]);
}

function expectEqual(name, actual, expected) {
  if (actual !== expected) fail(name, `expected ${expected}, got ${actual}`);
  else pass(name, String(actual));
}

function expectIncludes(name, actual, snippet) {
  if (!actual.includes(snippet)) fail(name, `missing ${snippet}`);
  else pass(name, "present");
}

await main();
